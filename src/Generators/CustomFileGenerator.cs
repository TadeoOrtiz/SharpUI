using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Xml;
using System.Xml.Linq;

namespace Components
{
  [Generator]
  public class CustomFileGenerator : IIncrementalGenerator
  {
    // Si usas un record, la comparación de igualdad del contenido es automática
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
      var sharpFiles = context.AdditionalTextsProvider
            .Where(file => Path.GetExtension(file.Path).Equals(".sharp", StringComparison.OrdinalIgnoreCase))
            .Select(static (file, ct) =>
            {
              var text = file.GetText(ct);
              return (
                FileName: Path.GetFileName(file.Path),
                ClassName: Path.GetFileNameWithoutExtension(file.Path),
                Content: text?.ToString() ?? string.Empty);
            });



      context.RegisterSourceOutput(sharpFiles, static (spc, data) =>
      {

        var sb = new StringBuilder();

        try
        {
          XDocument doc = XDocument.Parse(data.Content);

          sb.AppendLine("// <auto-generated/>");
          sb.AppendLine("using System;");
          sb.AppendLine();

          sb.AppendLine("namespace SampleProject.Generated");
          sb.AppendLine("{");
          sb.AppendLine($"    public class {data.ClassName} : SharpUI.Components.Component");
          sb.AppendLine("    {");
          sb.AppendLine("        public override void Initialize()");
          sb.AppendLine("        {");

          if (doc.Root != null)
          {
            var tagCounters = new Dictionary<string, int>();
            ProcessNode("", doc.Root, sb, tagCounters);
          }

          sb.AppendLine("        }");
          sb.AppendLine("    }");
          sb.AppendLine("}");

          string source = sb.ToString();
          spc.AddSource($"{data.ClassName}.g.cs", source);
        }
        catch (XmlException ex)
        {
          var descriptor = new DiagnosticDescriptor(
              id: "SHARP001",
              title: "Sharp Inválido",
              messageFormat: "El archivo '{0}' no es un Sharp válido: {1}",
              category: "CustomFileGenerator",
              defaultSeverity: DiagnosticSeverity.Warning,
              isEnabledByDefault: true);

          spc.ReportDiagnostic(Diagnostic.Create(descriptor, Location.None, data.FileName, ex.Message));
        }
      });
    }

    private static void ProcessNode(string parent, XElement node, StringBuilder sb, Dictionary<string, int> tagCounter)
    {
      string tagName = node.Name.LocalName;
      tagCounter.TryGetValue(tagName, out int count);
      count++;
      tagCounter[tagName] = count;

      string varName = $"{tagName}_{count}";

      sb.AppendLine($"            // Etiqueta: <{tagName}>");
      sb.AppendLine($"            var {varName} = new SharpUI.Components.{tagName}();");

      foreach (XAttribute attr in node.Attributes())
      {

        sb.AppendLine($"            // -> Atributo: {attr.Name.LocalName} = {attr.Value}");
        if (attr.Name.LocalName == "BackgroundColor")
        {
          sb.AppendLine($"            {varName}.{attr.Name.LocalName} = SkiaSharp.SKColors.{attr.Value};");
        }
        else
          sb.AppendLine($"            {varName}.{attr.Name.LocalName} = {attr.Value};");
      }

      if (!string.IsNullOrEmpty(parent))
        sb.AppendLine($"            {parent}.AddChild({varName});");
      else
        sb.AppendLine($"            AddChild({varName});");
      foreach (XElement child in node.Elements())
      {
        ProcessNode(varName, child, sb, tagCounter);
      }
    }
  }
}